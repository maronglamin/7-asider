#!/usr/bin/env node
/**
 * Writes src/config/oauth.generated.ts from .env (gitignored).
 * Client IDs are public OAuth identifiers, not secrets — but we keep them out of committed source.
 */
const fs = require('fs');
const path = require('path');

require('dotenv').config({ path: path.join(__dirname, '../.env') });

const outPath = path.join(__dirname, '../src/config/oauth.generated.ts');
const web = (process.env.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID || '').trim();
const android = (process.env.EXPO_PUBLIC_GOOGLE_ANDROID_CLIENT_ID || '').trim();
const ios = (process.env.EXPO_PUBLIC_GOOGLE_IOS_CLIENT_ID || '').trim();

const content = `// AUTO-GENERATED by scripts/generate-oauth-config.cjs — do not edit or commit.
export const GOOGLE_WEB_CLIENT_ID = ${JSON.stringify(web)};
export const GOOGLE_ANDROID_CLIENT_ID = ${JSON.stringify(android)};
export const GOOGLE_IOS_CLIENT_ID = ${JSON.stringify(ios)};
`;

fs.writeFileSync(outPath, content, 'utf8');
console.log('[generate-oauth-config] wrote', path.relative(process.cwd(), outPath));

if (!web && process.env.npm_lifecycle_event === 'build:web') {
  console.warn(
    '[generate-oauth-config] EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID is empty — web build will fetch client ID from GET /auth/public-config at runtime.',
  );
}
